package Basics;

public class Arithmetic_operation_on_int {
    public static void main(String [] args) {
        int x = 69 , y = 10;
        double a = 69;
        double b = 10;
        System.out.println(a + b);
        System.out.println(x + y);
        System.out.println(a - b);
        System.out.println(x - y);
        System.out.println(a * b);
        System.out.println(x * y);
        System.out.println(a / b);
        System.out.println(x / y);
    }
}
