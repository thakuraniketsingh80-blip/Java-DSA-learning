package Basics;

public class VariablesBasic {
    public static void main(String[] args) {
        int x;                  // declaration
        x = 10;                   // initialization
        int y;                  // declaration
        y = 5;                    // initialization
        System.out.println(x);
        System.out.println(y);
        System.out.println(x+y);
        x = 14;                   // re-initialization
        System.out.println(x);
    }
}
