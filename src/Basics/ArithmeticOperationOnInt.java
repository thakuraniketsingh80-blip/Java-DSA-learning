package Basics;

public class ArithmeticOperationOnInt {
    public static void main(String [] args) {
        int x = 69 , y = 10;
        double a = 100;
        double b = 6;
        System.out.println(a + b);
        System.out.println(x + y);
        System.out.println(a - b);
        System.out.println(x - y);
        System.out.println(a * b);
        System.out.println(x * y);
        System.out.println(a / b);
        System.out.println(x / y);
    }
}
